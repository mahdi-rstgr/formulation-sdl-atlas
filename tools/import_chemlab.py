"""Import the ChemLab-Assets instrument library (MBZUAI) into the assemblab catalogue.

    python tools/import_chemlab.py            # reads the public catalogue, writes data/chemlab.js and assets/img/chemlab/*.webp

Source: https://mbzuai-nlp.github.io/ChemLab-Assets/ (data/catalog.json) and the Hugging Face dataset
https://huggingface.co/datasets/MBZUAI/ChemLab-Assets. Assets are CC BY-NC 4.0 (attribution, non-commercial);
the GLB models are not copied into this repository: the 3D views stream them from the dataset on demand, and only
the small thumbnails are stored here, with credit on every entry.

Each instrument becomes one catalogue entry with: id "cl-<slug>", name, maker, model, the assemblab category it
belongs to, the capabilities it adds to a cell, its size (m), its GLB path and up axis. Instruments the catalogue
already has with its own model (Quantos, THINKY ARE-310, PreciseFlex 400, Opentrons Flex) are skipped.
"""
import json, re, sys, urllib.request
from pathlib import Path

PAGE = "https://mbzuai-nlp.github.io/ChemLab-Assets/"
ROOT = Path(__file__).resolve().parent.parent
OUT_JS = ROOT / "data" / "chemlab.js"
THUMBS = ROOT / "assets" / "img" / "chemlab"
SKIP = re.compile(r"Quantos|ARE-310|PreciseFlex 400|Opentrons Flex", re.I)

DOMAIN_CAT = {   # ChemLab domain -> assemblab parts category
    "metrology": "station", "spectroscopy": "analysis", "chromatography": "analysis", "elemental": "analysis", "imaging": "analysis",
    "particles": "analysis", "thermal": "analysis", "electrochem": "analysis", "bio": "analysis", "sampling": "analysis",
    "synthesis": "prep", "separation": "prep", "digestion": "prep", "materials": "prep", "facility": "facility", "automation": "facility",
}
def category(a):
    n = a["n"]
    if re.search(r"powder dosing", n, re.I): return "powder"
    if re.search(r"liquid-handling robot", n, re.I): return "platform"
    if re.search(r"robot arm", n, re.I): return "arm"
    if re.search(r"syringe pump", n, re.I): return "liquid"
    return DOMAIN_CAT[a["d"]]
def caps(a, cat):
    n, out = a["n"].lower(), set()
    if "balance" in n: out.add("weigh")
    if re.search(r"stirrer|shaker|mixer|disperser|ball mill|homogeni", n): out.add("mix")
    if re.search(r"syringe pump|liquid-handling", n): out.add("liquids")
    if "powder dosing" in n: out |= {"powders", "weigh"}
    if "robot arm" in n: out.add("move")
    if cat == "analysis" or re.search(r"meter|analy[sz]er|refractometer|turbidimeter|melting-point|rheometer|tensiometer", n): out.add("characterize")
    return sorted(out)

def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "assemblab-import"}), timeout=60) as r: return r.read()

def main():
    cat_json = json.loads(get(PAGE + "data/catalog.json"))
    domains = {d["key"]: d["name"] for d in cat_json["domains"]}
    THUMBS.mkdir(parents=True, exist_ok=True)
    rows, skipped = [], []
    for a in cat_json["assets"]:
        if SKIP.search(f'{a["n"]} {a["mk"]} {a["md"]}'): skipped.append(f'{a["n"]} ({a["mk"]} {a["md"]})'); continue
        slug = a["s"].replace("_", "-"); cat = category(a)
        thumb = THUMBS / f"{slug}.webp"
        if not thumb.exists():
            try: thumb.write_bytes(get(f"{PAGE}media/thumb/{a['s']}.webp"))
            except Exception as e: print("  no thumbnail for", a["s"], e, file=sys.stderr)
        rows.append({"id": "cl-" + slug, "code": a["c"], "name": a["n"], "maker": a["mk"], "model": a["md"], "domain": a["d"], "domainName": domains[a["d"]],
                     "cat": cat, "caps": caps(a, cat), "size": [round(x, 4) for x in a["sz"]], "up": a["up"], "glb": a["f"]["glb"],
                     "thumb": thumb.name if thumb.exists() else None, "panel": a.get("pu") or None, "joints": sum((a.get("jt") or {}).values())})
    head = ("/* GENERATED by tools/import_chemlab.py from ChemLab-Assets (MBZUAI), release " + str(cat_json.get("release", "1.5.0")) + ".\n"
            " * 3D models: https://huggingface.co/datasets/MBZUAI/ChemLab-Assets · CC BY-NC 4.0 (attribution, non-commercial use only).\n"
            " * Models stream from CHEMLAB_BASE on demand; thumbnails are in assets/img/chemlab/. Do not edit by hand. */\n")
    js = head + f'export const CHEMLAB_BASE = {json.dumps(cat_json["base"])};\n'
    js += 'export const CHEMLAB_CREDIT = { name: "ChemLab-Assets (MBZUAI)", url: "https://mbzuai-nlp.github.io/ChemLab-Assets/", license: "CC BY-NC 4.0", licenseUrl: "https://creativecommons.org/licenses/by-nc/4.0/" };\n'
    js += "export const CHEMLAB = [\n" + ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in rows) + "\n];\n"
    OUT_JS.write_text(js, encoding="utf-8", newline="\n")
    print(f"{len(rows)} instruments written to {OUT_JS.relative_to(ROOT)}; {len(skipped)} skipped (already in the catalogue): " + "; ".join(skipped))

if __name__ == "__main__":
    main()
